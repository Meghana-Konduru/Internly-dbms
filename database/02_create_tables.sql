-- 1. COMPANIES
CREATE TABLE companies (
    company_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_name VARCHAR(150) NOT NULL,
    industry VARCHAR(100),
    location VARCHAR(150)
);

-- 2. RECRUITERS
CREATE TABLE recruiters (
    recruiter_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    company_id INTEGER NOT NULL,

    CONSTRAINT fk_recruiter_company
        FOREIGN KEY (company_id)
        REFERENCES companies(company_id)
        ON DELETE RESTRICT,

    CONSTRAINT uq_recruiter_company
        UNIQUE (recruiter_id, company_id)
);

-- 3. STUDENTS
CREATE TABLE students (
    student_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    department VARCHAR(100),
    graduation_year INTEGER,
    resume_url TEXT,

    CONSTRAINT chk_graduation_year
        CHECK (
            graduation_year IS NULL
            OR graduation_year BETWEEN 2000 AND 2100
        )
);

-- 4. JOBS
CREATE TABLE jobs (
    job_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recruiter_id INTEGER NOT NULL,
    company_id INTEGER NOT NULL,
    title VARCHAR(150) NOT NULL,
    description TEXT,
    location VARCHAR(150),
    deadline DATE,
    status VARCHAR(30) NOT NULL DEFAULT 'open',

    CONSTRAINT fk_job_company
        FOREIGN KEY (company_id)
        REFERENCES companies(company_id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_job_recruiter_company
        FOREIGN KEY (recruiter_id, company_id)
        REFERENCES recruiters(recruiter_id, company_id)
        ON DELETE RESTRICT,

    CONSTRAINT chk_job_status
        CHECK (status IN ('open', 'closed', 'paused')),

    CONSTRAINT chk_job_deadline
        CHECK (deadline IS NULL OR deadline >= DATE '2000-01-01')
);

-- 5. APPLICATIONS
CREATE TABLE applications (
    application_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id INTEGER NOT NULL,
    job_id INTEGER NOT NULL,
    applied_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(30) NOT NULL DEFAULT 'pending',

    CONSTRAINT fk_application_student
        FOREIGN KEY (student_id)
        REFERENCES students(student_id)
        ON DELETE CASCADE,

    CONSTRAINT fk_application_job
        FOREIGN KEY (job_id)
        REFERENCES jobs(job_id)
        ON DELETE CASCADE,

    CONSTRAINT uq_student_job
        UNIQUE (student_id, job_id),

    CONSTRAINT chk_application_status
        CHECK (
            status IN (
                'pending',
                'shortlisted',
                'rejected',
                'accepted',
                'withdrawn'
            )
        )
);

-- 6. SKILLS
CREATE TABLE skills (
    skill_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skill_name VARCHAR(100) NOT NULL UNIQUE
);

-- 7. STUDENT_SKILLS
CREATE TABLE student_skills (
    student_id INTEGER NOT NULL,
    skill_id INTEGER NOT NULL,
    proficiency VARCHAR(30),

    PRIMARY KEY (student_id, skill_id),

    CONSTRAINT fk_student_skill_student
        FOREIGN KEY (student_id)
        REFERENCES students(student_id)
        ON DELETE CASCADE,

    CONSTRAINT fk_student_skill_skill
        FOREIGN KEY (skill_id)
        REFERENCES skills(skill_id)
        ON DELETE CASCADE,

    CONSTRAINT chk_proficiency
        CHECK (
            proficiency IS NULL
            OR proficiency IN (
                'Beginner',
                'Intermediate',
                'Advanced',
                'Expert'
            )
        )
);

-- 8. JOB_SKILLS
CREATE TABLE job_skills (
    job_id INTEGER NOT NULL,
    skill_id INTEGER NOT NULL,

    PRIMARY KEY (job_id, skill_id),

    CONSTRAINT fk_job_skill_job
        FOREIGN KEY (job_id)
        REFERENCES jobs(job_id)
        ON DELETE CASCADE,

    CONSTRAINT fk_job_skill_skill
        FOREIGN KEY (skill_id)
        REFERENCES skills(skill_id)
        ON DELETE CASCADE
);

-- 9. CERTIFICATIONS
CREATE TABLE certifications (
    certification_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    certification_name VARCHAR(150) NOT NULL,
    issuing_organization VARCHAR(150)
);

-- 10. STUDENT_CERTIFICATIONS
CREATE TABLE student_certifications (
    student_id INTEGER NOT NULL,
    certification_id INTEGER NOT NULL,
    issue_date DATE NOT NULL,
    expiry_date DATE,

    PRIMARY KEY (student_id, certification_id),

    CONSTRAINT fk_student_cert_student
        FOREIGN KEY (student_id)
        REFERENCES students(student_id)
        ON DELETE CASCADE,

    CONSTRAINT fk_student_cert_certification
        FOREIGN KEY (certification_id)
        REFERENCES certifications(certification_id)
        ON DELETE CASCADE,

    CONSTRAINT chk_certification_dates
        CHECK (
            expiry_date IS NULL
            OR expiry_date >= issue_date
        )
);

